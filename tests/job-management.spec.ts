import { test, expect } from "@playwright/test";
import { mockBackend } from "./helpers/backend";
import { createWorkspace } from "../src/workspaces/model";

test("job dashboard saves its plan, tasks, and notes without mixing customer jobs", async ({ page }) => {
  const backend = mockBackend();
  const customerId = "workboard-customer";
  const workspace = createWorkspace();
  workspace.customerId = customerId;
  Object.assign(workspace.record.customer, { customerName: "Workboard Customer", jobNumber: "FW-WORK-1", lossAddress: "100 Main St" });
  expect(backend.post({ action: "saveCustomer", customer: { id: customerId, name: "Workboard Customer", revision: 0, createdAt: "2026-10-26", updatedAt: "2026-10-26" }, expectedRevision: 0, mutationId: "customer-seed" }).ok).toBe(true);
  expect(backend.post({ action: "saveWorkspace", workspace, expectedRevision: 0, mutationId: "job-seed" }).ok).toBe(true);
  expect(backend.post({ action: "saveTask", task: { id: "other-job-task", customerId, workspaceId: "other-job", title: "Other job private task", status: "open" }, expectedRevision: 0, mutationId: "other-job-task-seed" }).ok).toBe(true);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", async route => {
    const request = route.request(), url = new URL(request.url());
    if (["localhost", "127.0.0.1"].includes(url.hostname) && !url.pathname.includes("__api__")) return route.continue();
    if (!["fetch", "xhr"].includes(request.resourceType())) return route.abort();
    const body = request.method() === "POST" ? JSON.parse(request.postData() || "{}") : Object.fromEntries(url.searchParams);
    return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(request.method() === "POST" ? backend.post(body) : backend.get(body)) });
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/#/workspaces/${workspace.id}`);
  const plan = page.getByRole("region", { name: "Job plan", exact: true });
  await plan.getByRole("combobox", { name: "Job status", exact: true }).selectOption("in_progress");
  await plan.getByLabel("Project manager", { exact: true }).fill("Jordan");
  await plan.getByLabel("Planned start", { exact: true }).fill("2026-11-01");
  await plan.getByLabel("Target finish", { exact: true }).fill("2026-12-01");
  await plan.getByRole("button", { name: "Save job plan", exact: true }).click();
  const tasks = page.getByRole("region", { name: "Job tasks", exact: true });
  await tasks.getByLabel("Task", { exact: true }).fill("Confirm site access");
  await tasks.getByLabel("Assignee", { exact: true }).fill("Casey");
  await tasks.getByLabel("Due date", { exact: true }).fill("2026-11-02");
  await tasks.getByRole("button", { name: "Add task", exact: true }).click();
  await expect(tasks.getByText("Confirm site access", { exact: true })).toBeVisible();
  await expect(tasks.getByText("Other job private task", { exact: true })).toHaveCount(0);
  await tasks.getByRole("button", { name: "Edit task Confirm site access", exact: true }).click();
  await tasks.getByLabel("Edit task", { exact: true }).fill("Confirm lockbox access");
  await tasks.getByRole("button", { name: "Save task", exact: true }).click();
  await tasks.getByRole("checkbox", { name: 'Mark "Confirm lockbox access" done', exact: true }).click();
  await tasks.getByRole("button", { name: /^Completed/ }).click();
  await expect(tasks.getByText("Confirm lockbox access", { exact: true })).toBeVisible();
  const notes = page.getByRole("region", { name: "Job notes & updates", exact: true });
  await notes.getByLabel("Add a note", { exact: true }).fill("Crew can use the side entrance.");
  await notes.getByRole("button", { name: "Add note", exact: true }).click();
  await expect.poll(() => backend.post({ action: "listTasks", customerId }).tasks.find((row: { workspaceId: string }) => row.workspaceId === workspace.id)?.status).toBe("done");
  await expect.poll(() => backend.post({ action: "listActivities", customerId }).activities.length).toBe(1);
  await expect.poll(() => backend.post({ action: "openWorkspace", workspaceId: workspace.id }).workspace.stage).toBe("in_progress");
  await page.screenshot({ path: "tmp/job-management-desktop.png", fullPage: true });
  await page.reload();
  await expect(plan.getByLabel("Target finish", { exact: true })).toHaveValue("2026-12-01");
  await expect(notes.getByText("Crew can use the side entrance.", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "tmp/job-management-phone.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
